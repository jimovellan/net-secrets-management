export function getLanguage(): Language {
    const preference = vscode.workspace.getConfiguration('net-secrets-manager').get<string>('language', 'en');
    if (preference !== 'auto' && supportedLanguages.includes(preference as Language)) {
        return preference as Language;
    }

    const locale = vscode.env.language.toLowerCase();
    if (locale.startsWith('zh')) return 'zh-CN';
    if (locale.startsWith('hi')) return 'hi';
    if (locale.startsWith('es')) return 'es';
    if (locale.startsWith('fr')) return 'fr';
    if (locale.startsWith('ar')) return 'ar';
    if (locale.startsWith('bn')) return 'bn';
    if (locale.startsWith('pt')) return 'pt-BR';
    if (locale.startsWith('ru')) return 'ru';
    if (locale.startsWith('ur')) return 'ur';
    return 'en';
}

export function getMessages(language: Language = getLanguage()): Messages & UXMessages & BrowserMessages {
    return { ...translations[language], ...uxTranslations[language], ...browserTranslations[language] };
}

export function t(key: MessageKey, values: Record<string, string> = {}): string {
    return getMessages()[key].replace(/\{(\w+)\}/g, (_match, name: string) => values[name] ?? '');
}
